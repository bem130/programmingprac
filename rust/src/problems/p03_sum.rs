// ============================================
// 問題3: 合計値 (難易度: ★☆☆☆☆)
// ============================================
// 整数のスライスを受け取り、その合計を返してください。
//
// 例:
//   sum(&[1, 2, 3])     => 6
//   sum(&[])             => 0
//   sum(&[-1, 1])        => 0
//
// ヒント: for ループか .iter().sum() を使おう

pub fn sum(numbers: &[i32]) -> i32 {
    numbers.iter().sum()
}
