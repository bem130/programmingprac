// ============================================
// 問題2: FizzBuzz (難易度: ★☆☆☆☆)
// ============================================
// 数値を受け取り、以下のルールで文字列を返してください:
//   - 3と5の両方で割り切れる → "FizzBuzz"
//   - 3で割り切れる → "Fizz"
//   - 5で割り切れる → "Buzz"
//   - それ以外 → その数値の文字列 (例: 7 → "7")
//
// ヒント: if/else と % (剰余演算子) を使おう

pub fn fizzbuzz(n: u32) -> String {
    match (n%3,n%5) {
        (0,0)=>"FizzBuzz".to_string(),
        (0,_)=>"Fizz".to_string(),
        (_,0)=>"Buzz".to_string(),
        _=>n.to_string(),
    }
}
