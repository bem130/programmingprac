// ============================================
// 問題9: 中央値 (難易度: ★★★☆☆)
// ============================================
// 整数のスライスの中央値を返してください。
// - 要素数が奇数: 真ん中の値
// - 要素数が偶数: 真ん中2つの平均
// - 空の場合: 0.0
//
// 例:
//   median(&[3, 1, 2])    => 2.0
//   median(&[4, 1, 3, 2]) => 2.5
//   median(&[])            => 0.0
//
// ヒント: まずソートしてから中央の要素を取り出そう
//         元のスライスを変更しないように .to_vec() でコピーすること

pub fn median(numbers: &[i32]) -> f64 {
    let mut vec:Vec<i32> = numbers.to_vec();
    vec.sort();
    let l = vec.len();
    match (l,l%2) {
        (0,_) => 0.0,
        (_,0) => Into::<f64>::into(*vec.get(l/2-1).unwrap()+*vec.get(l/2).unwrap())/2.0,
        (_,_) => Into::<f64>::into(*vec.get(l/2).unwrap()),
    }
}
