// ============================================
// 問題20: 行列の積 (難易度: ★★★☆☆)
// ============================================
// 2つの行列の積を計算してください。
// 行列は Vec<Vec<i64>> で表現します。
//
// 行列の積の定義:
//   C[i][j] = Σ A[i][k] * B[k][j]  (k = 0..A の列数)
//
// 例:
//   mat_mul( [[1,2],[3,4]], [[5,6],[7,8]] )
//   => [[19,22],[43,50]]
//
// 前提: A の列数 == B の行数 (常に成立する入力のみ与えられる)
//
// ヒント:
//   - 三重ループ: i, j, k
//   - A の行数: a.len()
//   - A の列数: a[0].len()
//   - B の列数: b[0].len()

pub fn mat_mul(a: &Vec<Vec<i64>>, b: &Vec<Vec<i64>>) -> Vec<Vec<i64>> {
    let rows = a.len();
    let cols = b[0].len();
    let common = a[0].len();
    let mut res = vec![vec![0; cols]; rows];
    for i in 0..rows {
        for j in 0..cols {
            for k in 0..common {
                res[i][j] += a[i][k] * b[k][j];
            }
        }
    }
    res
}
