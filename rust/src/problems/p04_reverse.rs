// ============================================
// 問題4: 文字列の反転 (難易度: ★★☆☆☆)
// ============================================
// 文字列を受け取り、逆順にした新しい文字列を返してください。
//
// 例:
//   reverse("hello") => "olleh"
//   reverse("Rust")  => "tsuR"
//   reverse("")      => ""
//
// ヒント: .chars().rev() を使おう

pub fn reverse(s: &str) -> String {
    s.chars().rev().collect()
}
