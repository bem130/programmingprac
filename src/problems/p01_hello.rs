// ============================================
// 名前を受け取って "Hello, {名前}!" という文字列を返す関数を書いてください。
//
// 例:
//   greet("World")  => "Hello, World!"
//   greet("Rust")   => "Hello, Rust!"
//
// ヒント: format! マクロを使おう

pub fn greet(name: &str) -> String {
    format!("Hello, {}!",name)
}
